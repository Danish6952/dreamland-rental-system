// Concatenates supabase/migrations/*.sql into one file you can paste into the
// Supabase SQL Editor in a single run (first-time setup of a new project).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const dir = 'supabase/migrations';
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const out = files.map((f) => `-- ==================== ${f} ====================\n${readFileSync(`${dir}/${f}`, 'utf8')}`).join('\n\n');
writeFileSync('supabase/all-migrations.sql', `-- GENERATED by npm run db:bundle — do not edit. Run once on a NEW, empty project.\n\n${out}`);
console.log(`supabase/all-migrations.sql written (${files.length} files)`);
